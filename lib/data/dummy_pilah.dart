import 'dart:math' as math;

enum PilahCategory {
  organik('Organik', 0xFF2E9E5B),
  anorganik('Anorganik', 0xFF2F6FED),
  b3('B3', 0xFFE04F5F),
  residu('Residu', 0xFF8A948D);

  const PilahCategory(this.label, this.colorValue);

  final String label;
  final int colorValue;
}

class PilahLocation {
  const PilahLocation({
    required this.id,
    required this.name,
    required this.description,
    required this.category,
    required this.address,
    required this.city,
    required this.latitude,
    required this.longitude,
    required this.rating,
    this.openHour = '08.00',
    this.closeHour = '17.00',
    this.closedDays = const [7], // DateTime.weekday: 1 = Senin ... 7 = Minggu
    this.phone,
    this.accepts = const [],
  });

  final String id;
  final String name;
  final String description;
  final PilahCategory category;
  final String address;
  final String city; // kota/kabupaten
  final double latitude;
  final double longitude;
  final double rating;
  final String openHour; // format "HH.mm"
  final String closeHour; // format "HH.mm"
  final List<int> closedDays;
  final String? phone;
  final List<String> accepts;

  /// Jarak garis lurus (Haversine) dalam kilometer.
  double distanceKmFrom(double lat, double lng) {
    const earthRadiusKm = 6371.0;
    final dLat = _rad(lat - latitude);
    final dLng = _rad(lng - longitude);
    final a = math.sin(dLat / 2) * math.sin(dLat / 2) +
        math.cos(_rad(latitude)) *
            math.cos(_rad(lat)) *
            math.sin(dLng / 2) *
            math.sin(dLng / 2);
    return earthRadiusKm * 2 * math.atan2(math.sqrt(a), math.sqrt(1 - a));
  }

  bool isOpenAt(DateTime now) {
    if (closedDays.contains(now.weekday)) return false;
    final minutesNow = now.hour * 60 + now.minute;
    return minutesNow >= _minutes(openHour) && minutesNow < _minutes(closeHour);
  }

  /// Contoh: "Buka · tutup 17.00" atau "Tutup".
  String statusLabel(DateTime now) =>
      isOpenAt(now) ? 'Buka · tutup $closeHour' : 'Tutup';

  static double _rad(double deg) => deg * math.pi / 180;

  static int _minutes(String hhmm) {
    final parts = hhmm.split('.');
    return int.parse(parts[0]) * 60 + int.parse(parts[1]);
  }
}

/// 0,8 km -> "800 m", 1,4 km -> "1,4 km", 120 km -> "120 km".
String formatDistance(double km) {
  if (km < 1) return '${(km * 1000).round()} m';
  final text = km < 100 ? km.toStringAsFixed(1) : km.round().toString();
  return '${text.replaceAll('.', ',')} km';
}

/// Cari berdasarkan nama, deskripsi, alamat, kota, atau jenis sampah yang
/// diterima. Jika [userLat] dan [userLng] diisi, hasil diurutkan terdekat.
List<PilahLocation> searchPilah({
  String query = '',
  PilahCategory? category,
  double? userLat,
  double? userLng,
}) {
  final q = query.trim().toLowerCase();
  final hasil = dummyPilahLocations.where((p) {
    if (category != null && p.category != category) return false;
    if (q.isEmpty) return true;
    final haystack = [
      p.name,
      p.description,
      p.address,
      p.city,
      p.category.label,
      ...p.accepts,
    ].join(' ').toLowerCase();
    return haystack.contains(q);
  }).toList();

  if (userLat != null && userLng != null) {
    hasil.sort((a, b) => a
        .distanceKmFrom(userLat, userLng)
        .compareTo(b.distanceKmFrom(userLat, userLng)));
  }
  return hasil;
}

